export const sampleTrajectory: Trajectory = {
  schemaVersion: 1,
  id: "create-order--1",
  scenarioId: "create-order",
  title: 'Create an "order" with a name',
  source: { goalId: "goal_x", magpiRoot: "/tmp", magpiVersion: "0.1.8", locatorRecovery: "ledger-target" },
  startPath: "/order",
  steps: [
    { intent: "enter name", action: { kind: "fill", target: { by: "label", text: "Your name", exact: true }, value: { literal: "Ada \\ `Lovelace` ${x}" } } },
    { intent: "enter email", action: { kind: "fill", target: { by: "placeholder", text: "Email" }, value: { unique: "qa+{n}@example.com" } } },
    { intent: "choose size", action: { kind: "select", target: { by: "role", role: "combobox", name: "Size", exact: true }, value: { literal: "L" } } },
    { intent: "accept terms", action: { kind: "check", target: { by: "testId", id: "terms" } } },
    { intent: "secret", action: { kind: "fill", target: { by: "label", text: "Password" }, value: { env: "SHOP_PASSWORD" } } },
    { intent: "place the order — a very long intent that keeps going and going well past the eighty char limit", action: { kind: "click", target: { by: "role", role: "button", name: "Place order", exact: true } }, waitFor: [{ kind: "url_includes", text: "/orders/" }] },
    { intent: "open details", action: { kind: "click", target: { by: "text", text: "Details" } } },
  ],
  assertions: [
    { kind: "text_visible", text: "Order placed ✓" },
    { kind: "text_absent", text: "Error" },
    { kind: "control_exists", role: "a", name: "Back" },
    { kind: "value_equals", name: "Your name", text: "Ada" },
    { kind: "title_includes", text: "Shop (beta)" },
    { kind: "dialog_open", open: false },
    { kind: "all", of: [{ kind: "no_console_error" }] },
  ],
  status: "draft",
  repairs: [],
};

test("emitter output is deterministic and matches the snapshot", () => {
  const source = emitSpec(sampleTrajectory);
  assert.equal(source, emitSpec(structuredClone(sampleTrajectory)));
  assert.deepEqual(validateTrajectory(sampleTrajectory), []);
  const expected = [
    "// Generated by magpi-test from trajectory create-order--1.",
    "// Do not edit by hand: change the scenario or trajectory and regenerate (QD13).",
    'import { test, expect } from "@playwright/test";',
    "",
    'test("Create an \\"order\\" with a name", async ({ page }) => {',
    "  const consoleErrors: string[] = [];",
    '  page.on("console", (message) => { if (message.type() === "error") consoleErrors.push(message.text()); });',
    "  const runId = `${test.info().testId}-${Date.now().toString(36)}`;",
    '  await page.goto("/order");',
    '  await test.step("enter name", async () => {',
    '    await page.getByLabel("Your name", { exact: true }).fill("Ada \\\\ `Lovelace` ${x}");',
    "  });",
    '  await test.step("enter email", async () => {',
    '    await page.getByPlaceholder("Email").fill(`qa+${runId}@example.com`);',
    "  });",
    '  await test.step("choose size", async () => {',
    '    await page.getByRole("combobox", { name: "Size", exact: true }).selectOption("L");',
    "  });",
    '  await test.step("accept terms", async () => {',
    '    await page.getByTestId("terms").check();',
    "  });",
    '  await test.step("secret", async () => {',
    '    await page.getByLabel("Password", { exact: true }).fill((process.env["SHOP_PASSWORD"] ?? (() => { throw new Error("SHOP_PASSWORD is not set"); })()));',
    "  });",
    '  await test.step("place the order — a very long intent that keeps going and going well past the...", async () => {',
    '    await page.getByRole("button", { name: "Place order", exact: true }).click();',
    '    await expect(page).toHaveURL(new RegExp("\\\\/orders\\\\/"));',
    "  });",
    '  await test.step("open details", async () => {',
    '    await page.getByText("Details").click();',
    "  });",
    '  await expect(page.getByText("Order placed ✓").first()).toBeVisible();',
    '  await expect(page.getByText("Error")).toHaveCount(0);',
    '  await expect(page.getByRole("link", { name: "Back" }).first()).toBeVisible();',
    '  await expect(page.getByLabel("Your name")).toHaveValue("Ada");',
    '  await expect(page).toHaveTitle(new RegExp("Shop \\\\(beta\\\\)"));',
    '  await expect(page.getByRole("dialog")).toHaveCount(0);',
    "  expect(consoleErrors).toEqual([]);",
    "});",
    "",
  ].join("\n");
  assert.equal(source, expected);
});

test("any / not are unsupported", () => {
  assert.throws(() => emitSpec({ ...sampleTrajectory, assertions: [{ kind: "any", of: [] }] }), UnsupportedAssertion);
  assert.throws(() => emitSpec({ ...sampleTrajectory, assertions: [{ kind: "not", of: { kind: "no_console_error" } }] }), UnsupportedAssertion);
});

test("emitted spec passes the no-AI guard and compiles under playwright --list", async () => {
  const source = emitSpec(sampleTrajectory);
  assert.deepEqual(checkNoAi(source), []);
  const { root, cleanup } = await tempTarget("target-nodocs");
  try {
    await writeFile(path.join(root, "a.spec.ts"), source);
    await writeFile(path.join(root, "playwright.config.ts"), 'import { defineConfig } from "@playwright/test";\nexport default defineConfig({ testDir: "." });\n');
    const bin = new URL("../../node_modules/.bin/playwright", import.meta.url).pathname;
    const out = execFileSync(bin, ["test", "--list", "--config", path.join(root, "playwright.config.ts")], { cwd: root, encoding: "utf8" });
    assert.match(out, /Create an "order" with a name/);
  } finally {
    await cleanup();
  }
});

test("guard rejects Magpi imports, fetch, and provider keys", () => {
  const ok = emitSpec(sampleTrajectory);
  assert.match(checkNoAi(ok.replace('import { test, expect } from "@playwright/test";', 'import { test, expect } from "@playwright/test";\nimport { x } from "@naiemk/magpi";')).join(), /forbidden import/);
  assert.match(checkNoAi(`${ok}\nawait fetch("https://x");`).join(), /fetch/);
  assert.match(checkNoAi(`${ok}\nprocess.env.OPENROUTER_API_KEY;`).join(), /API_KEY|openrouter/);
  assert.match(checkNoAi(ok.replace(/^\/\/ Generated.*\n/, "")).join(), /header/);
});
