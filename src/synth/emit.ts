import { assertionCode, locatorCode, usesConsole } from "./assertions.ts";
import type { Step, Trajectory, Value } from "./types.ts";

export const HEADER_PREFIX = "// Generated by magpi-test from trajectory";

const q = (value: string) => JSON.stringify(value);
const indent = (lines: string[], depth: number) => lines.map((line) => `${"  ".repeat(depth)}${line}`);

/** Pure: same trajectory → byte-identical source (test-synthesis.md "Emitter"). */
export function emitSpec(trajectory: Trajectory): string {
  const consoleCheck = usesConsole(trajectory.assertions);
  const needsUnique = trajectory.steps.some((s) => "value" in s.action && "unique" in s.action.value);
  const body: string[] = [];
  if (consoleCheck) {
    body.push("const consoleErrors: string[] = [];");
    body.push(`page.on("console", (message) => { if (message.type() === "error") consoleErrors.push(message.text()); });`);
  }
  if (needsUnique) body.push("const runId = `${test.info().testId}-${Date.now().toString(36)}`;");
  body.push(`await page.goto(${q(trajectory.startPath)});`);
  for (const step of trajectory.steps) {
    body.push(`await test.step(${q(stepTitle(step))}, async () => {`);
    body.push(...indent(stepLines(step), 1));
    body.push("});");
  }
  for (const assertion of trajectory.assertions) body.push(...assertionCode(assertion));
  return [
    `${HEADER_PREFIX} ${trajectory.id}.`,
    "// Do not edit by hand: change the scenario or trajectory and regenerate (QD13).",
    `import { test, expect } from "@playwright/test";`,
    "",
    `test(${q(trajectory.title)}, async ({ page }) => {`,
    ...indent(body, 1),
    "});",
    "",
  ].join("\n");
}

function stepTitle(step: Step): string {
  const title = step.intent.replace(/\s+/g, " ").trim() || step.action.kind;
  return title.length > 80 ? `${title.slice(0, 77)}...` : title;
}

function stepLines(step: Step): string[] {
  const a = step.action;
  const lines: string[] = [];
  switch (a.kind) {
    case "goto":
      lines.push(`await page.goto(${q(a.path)});`);
      break;
    case "click":
      lines.push(`await ${locatorCode(a.target)}.click();`);
      break;
    case "fill":
      lines.push(`await ${locatorCode(a.target)}.fill(${valueCode(a.value)});`);
      break;
    case "select":
      lines.push(`await ${locatorCode(a.target)}.selectOption(${valueCode(a.value)});`);
      break;
    case "check":
    case "uncheck":
      lines.push(`await ${locatorCode(a.target)}.${a.kind}();`);
      break;
    case "press":
      lines.push(`await ${locatorCode(a.target)}.press(${q(a.key)});`);
      break;
  }
  for (const wait of step.waitFor ?? []) lines.push(...assertionCode(wait));
  return lines;
}

function valueCode(value: Value): string {
  if ("literal" in value) return q(value.literal);
  if ("env" in value) return `(process.env[${q(value.env)}] ?? (() => { throw new Error(${q(`${value.env} is not set`)}); })())`;
  const template = value.unique.includes("{n}") ? value.unique : `${value.unique}-{n}`;
  const [before, after] = template.split("{n}");
  return `\`${escapeTemplate(before)}\${runId}${escapeTemplate(after)}\``;
}

function escapeTemplate(text: string): string {
  return text.replace(/[`\\$]/g, (c) => `\\${c}`);
}
