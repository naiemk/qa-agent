import path from "node:path";
import { renderScenarioMarkdown } from "../scenario/markdown.ts";
import type { Scenario } from "../scenario/types.ts";
import { writeText } from "../state/index.ts";

export function statusLine(scenario: Scenario): string {
  switch (scenario.status) {
    case "accepted":
      return `automated (${scenario.specFile ?? "specs/"})`;
    case "quarantined":
      return `quarantined (${scenario.quarantine?.suspected ?? "unknown"})`;
    case "skipped":
      return scenario.needsFixture?.length ? `needs-fixture (${scenario.needsFixture.join(", ")})` : `skipped`;
    default:
      return "pending";
  }
}

/** QD16: one file per area, in the guided format plus a status line. Pure rendering, no model. */
export function renderManual(scenarios: Scenario[]): Map<string, string> {
  const byArea = new Map<string, Scenario[]>();
  for (const scenario of scenarios) byArea.set(scenario.area, [...(byArea.get(scenario.area) ?? []), scenario]);
  const files = new Map<string, string>();
  for (const [area, list] of [...byArea].sort(([a], [b]) => a.localeCompare(b))) {
    const sorted = [...list].sort((a, b) => a.priority - b.priority || a.id.localeCompare(b.id));
    const header = `<!-- Manual test cases for area ${area}, generated by magpi-test. Move a corrected case to magpi-tests/scenarios/<id>.md to automate it. -->\n\n`;
    files.set(`${area}.md`, header + sorted.map((s) => renderScenarioMarkdown(s, statusLine(s))).join("\n---\n\n"));
  }
  return files;
}

/** Splits an area file back into per-case markdown with status lines stripped (round trip). */
export function splitManual(text: string): string[] {
  return text
    .split(/^---$/m)
    .map((chunk) => chunk.replace(/^<!--.*-->$/gm, "").replace(/^status: .*$/m, "").trim())
    .filter(Boolean);
}

export async function writeManual(manualDir: string, scenarios: Scenario[]): Promise<string[]> {
  const written: string[] = [];
  for (const [name, text] of renderManual(scenarios)) {
    const file = path.join(manualDir, name.replace(/[^a-z0-9._-]/gi, "-"));
    await writeText(file, text);
    written.push(file);
  }
  return written;
}
