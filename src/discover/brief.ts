/** The QA brief (QD14): one short file with fixed headings, committed by the user. */
export interface QaBrief {
  product: string;
  summary: string;
  users: string[];
  areas: { id: string; title: string; routes: string[]; source: string[] }[];
  flows: { title: string; area: string; why: string }[];
  testData: string[];
  offLimits: string[];
  fixtures: string[];
}

export class BriefFormatError extends Error {}

const SECTION_KEYS: Record<string, keyof QaBrief> = {
  product: "summary",
  "users and roles": "users",
  areas: "areas",
  "critical flows": "flows",
  "test data": "testData",
  "off-limits": "offLimits",
  "known fixtures": "fixtures",
};

export const GENERATED_HEADER = "<!-- generated by magpi-test init from the repo's docs; review me -->";
export const BRIEF_SOURCES = ["AGENTS.md", "CLAUDE.md", "QA.md", "README*", ".cursor/rules/**", "docs/**/*.md"];

export function parseBrief(text: string): QaBrief {
  const brief: QaBrief = { product: "", summary: "", users: [], areas: [], flows: [], testData: [], offLimits: [], fixtures: [] };
  let section: keyof QaBrief | undefined;
  const summary: string[] = [];
  for (const [index, raw] of text.split(/\r?\n/).entries()) {
    const line = raw.trim();
    if (!line || line.startsWith("<!--")) continue;
    if (line.startsWith("# ")) {
      const match = line.match(/^# QA brief:\s*(.+)$/i);
      if (!match) throw new BriefFormatError(`line ${index + 1}: title must be "# QA brief: <product>"`);
      brief.product = match[1].trim();
      continue;
    }
    if (line.startsWith("## ")) {
      const key = SECTION_KEYS[line.slice(3).trim().toLowerCase()];
      if (!key) throw new BriefFormatError(`line ${index + 1}: unknown heading "${line.slice(3).trim()}"`);
      section = key;
      continue;
    }
    if (!section) throw new BriefFormatError(`line ${index + 1}: text before the first section`);
    const item = line.replace(/^(?:[-*]|\d+[.)])\s+/, "").trim();
    if (section === "summary") summary.push(item);
    else if (section === "areas") brief.areas.push(parseArea(item, index + 1));
    else if (section === "flows") brief.flows.push(parseFlow(item, index + 1));
    else (brief[section] as string[]).push(item);
  }
  if (!brief.product) throw new BriefFormatError("missing # QA brief: <product>");
  brief.summary = summary.join(" ");
  return brief;
}

function parseArea(item: string, line: number): QaBrief["areas"][number] {
  const match = item.match(/^([a-z0-9][a-z0-9._-]*)\s*:\s*([^—]+?)(?:\s+—\s+(.*))?$/i);
  if (!match) throw new BriefFormatError(`line ${line}: area must be "<id>: <title> — routes: /a, /b — source: dir/"`);
  const rest = match[3] ?? "";
  const list = (key: string) => rest.match(new RegExp(`${key}:\\s*([^—]+)`))?.[1].split(",").map((s) => s.trim()).filter(Boolean) ?? [];
  return { id: match[1], title: match[2].trim(), routes: list("routes"), source: list("source") };
}

function parseFlow(item: string, line: number): QaBrief["flows"][number] {
  const match = item.match(/^(.+?)\s*\(([a-z0-9._-]+)\)\s*:\s*(.+)$/i);
  if (!match) throw new BriefFormatError(`line ${line}: flow must be "<title> (<area id>): <why>"`);
  return { title: match[1].trim(), area: match[2], why: match[3].trim() };
}

export function renderBrief(brief: QaBrief, header?: string): string {
  const out: string[] = [];
  if (header) out.push(header, "");
  out.push(`# QA brief: ${brief.product}`, "", "## Product", brief.summary || "-");
  const list = (title: string, items: string[]) => {
    out.push("", `## ${title}`);
    for (const item of items) out.push(`- ${item}`);
  };
  list("Users and roles", brief.users);
  list("Areas", brief.areas.map((a) => [`${a.id}: ${a.title}`, a.routes.length ? `routes: ${a.routes.join(", ")}` : "", a.source.length ? `source: ${a.source.join(", ")}` : ""].filter(Boolean).join(" — ")));
  list("Critical flows", brief.flows.map((f) => `${f.title} (${f.area}): ${f.why}`));
  list("Test data", brief.testData);
  list("Off-limits", brief.offLimits);
  list("Known fixtures", brief.fixtures);
  return `${out.join("\n")}\n`;
}

export function validateBriefJson(value: unknown): string[] {
  const b = value as QaBrief;
  if (!b || typeof b !== "object") return ["not an object"];
  const errors: string[] = [];
  if (!b.product) errors.push("product is required");
  for (const key of ["users", "areas", "flows", "testData", "offLimits", "fixtures"] as const) if (!Array.isArray(b[key])) errors.push(`${key} must be an array`);
  for (const [i, a] of (b.areas ?? []).entries()) if (!/^[a-z0-9][a-z0-9._-]*$/.test(a.id ?? "") || !a.title) errors.push(`areas[${i}] needs a lowercase id and title`);
  for (const [i, f] of (b.flows ?? []).entries()) if (!f.title || !f.area || !f.why) errors.push(`flows[${i}] needs title, area, why`);
  if (errors.length === 0) {
    try {
      parseBrief(renderBrief(b));
    } catch (error) {
      errors.push(`does not round-trip: ${(error as Error).message}`);
    }
  }
  return errors;
}

export interface CollectedDocs {
  files: { file: string; text: string }[];
  thin: boolean;
}

const PER_FILE_CHARS = 6000;
const TOTAL_CHARS = 30_000; // ~8k tokens

/** Reads the repo's own agent/docs files through the guard. Thin = nothing to build from. */
export async function collectDocs(files: FileAccess): Promise<CollectedDocs> {
  const collected: CollectedDocs["files"] = [];
  let total = 0;
  const names = await files.list(BRIEF_SOURCES);
  const priority = (file: string) => ["AGENTS.md", "CLAUDE.md", "QA.md"].includes(file) ? 0 : file.startsWith("README") ? 1 : 2;
  for (const file of names.sort((a, b) => priority(a) - priority(b) || a.localeCompare(b))) {
    if (total >= TOTAL_CHARS) break;
    const text = (await files.read(file)).slice(0, Math.min(PER_FILE_CHARS, TOTAL_CHARS - total));
    total += text.length;
    collected.push({ file, text });
  }
  const all = collected.map((c) => c.text).join("\n");
  const hasRoute = /(?:^|[\s`"'(])\/[a-z][a-z0-9-]*/m.test(all);
  const hasFlow = /^#{1,3}\s.*\b(flow|feature|usage|user|how to|guide|pages?|routes?)\b/im.test(all) || /\b(sign ?up|log ?in|create|checkout|pay|invoice|order|upload)\b/i.test(all);
  return { files: collected, thin: collected.length === 0 || !(hasRoute && hasFlow) };
}

export async function briefFromDocs(docs: CollectedDocs, model: ModelClient): Promise<QaBrief> {
  const { value } = await model.completeJson<QaBrief>({
    purpose: "brief",
    system:
      "You write a QA brief for a web application from its own documentation. Be concrete and short. " +
      "Only state what the documents support. Area ids are lowercase dotted or dashed words. " +
      "Critical flows are user-visible flows ordered by user value and risk (money, identity, data loss) first.",
    user: docs.files.map((d) => `=== ${d.file} ===\n${d.text}`).join("\n\n"),
    schemaHint:
      '{"product":"name","summary":"1-2 sentences","users":["role: what they do"],"areas":[{"id":"commerce","title":"Commerce","routes":["/create"],"source":["src/pages/"]}],' +
      '"flows":[{"title":"Create an invoice","area":"commerce","why":"merchants get paid"}],"testData":["..."],"offLimits":["..."],"fixtures":["email-otp"]}',
    validate: validateBriefJson,
  });
  return value;
}

/** Printed when the docs are too thin (exit code 3). The user's coding agent writes the brief. */
export function agentPrompt(briefPath: string, answerKey: string[]): string {
  return [
    `Read this repository and write a QA brief to ${briefPath}. Write only that file.`,
    "",
    "Use exactly this format (headings are fixed; keep each item to one line):",
    "",
    "# QA brief: <product name>",
    "## Product",
    "<one or two sentences: what the app is for>",
    "## Users and roles",
    "- <role>: <what they do>",
    "## Areas",
    "- <area id>: <title> — routes: /a, /b — source: <folders>",
    "## Critical flows",
    "- <flow title> (<area id>): <why it matters>",
    "## Test data",
    "- <accounts, seeded records, dev OTP, faucets available in the test environment>",
    "## Off-limits",
    "- <things a tester must never do>",
    "## Known fixtures",
    "- <webauthn, email-otp, funding, worker-tick, ...>",
    "",
    "Order critical flows by user value and risk (money, identity, data loss) first.",
    "Find routes in the router code and areas in the source tree.",
    ...(answerKey.length
      ? ["", "Do NOT open, read, or quote these files; they are a hidden benchmark:", ...answerKey.map((glob) => `- ${glob}`)]
      : []),
  ].join("\n");
}
